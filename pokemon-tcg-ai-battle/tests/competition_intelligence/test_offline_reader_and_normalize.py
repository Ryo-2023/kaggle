class TestNormalizeRuleBcJsonl:
    def test_produces_episodes_and_decisions(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        assert result.source_row_count > 0
        assert result.valid_row_count == result.source_row_count
        assert len(result.quarantined_rows) == 0
        assert len(result.episodes) == 6  # games=6 in the fixture
        assert len(result.decisions) > 0

    def test_episode_source_id_is_the_envelope_id_not_the_episode_id(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:envelope-42")
        for episode in result.episodes:
            assert episode.source_id == "local:envelope-42"
            assert episode.episode_id != "local:envelope-42"

    def test_raw_row_source_id_key_is_pinned_to_mean_episode_identity(self, rule_bc_jsonl_path: Path) -> None:
        # Independent-audit finding #5 (schema naming collision, minimal-fix
        # scope): a raw rule-bc-v1 row's own "source_id" key is NOT a
        # contracts.SourceEnvelope id -- it holds the row's *episode*
        # identity, unrelated to this function's own `source_id` keyword
        # argument (the actual envelope id, checked in the test above). This
        # test pins that specific mapping so a future schema change would
        # have to break it visibly, not silently.
        raw_row_source_ids = {row["source_id"] for _, row, _ in iter_rule_bc_rows(rule_bc_jsonl_path) if row is not None}
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:envelope-42")
        normalized_episode_ids = {episode.episode_id for episode in result.episodes}
        assert raw_row_source_ids == normalized_episode_ids
        assert "local:envelope-42" not in raw_row_source_ids

    def test_decision_indices_are_ordered_within_episode(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        by_episode: dict[str, list[int]] = {}
        for decision in result.decisions:
            by_episode.setdefault(decision.episode_id, []).append(decision.decision_index)
        for indices in by_episode.values():
            assert indices == sorted(indices)
            assert len(indices) == len(set(indices))  # no duplicate decision_index within an episode

    def test_stable_action_key_digests_reused_verbatim(self, rule_bc_jsonl_path: Path) -> None:
        raw_digests: set[str] = set()
        for _, row, _ in iter_rule_bc_rows(rule_bc_jsonl_path):
            assert row is not None
            raw_digests.update(action["digest"] for action in row["legal_actions"])
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        normalized_digests: set[str] = set()
        for decision in result.decisions:
            if decision.legal_action_keys:
                normalized_digests.update(decision.legal_action_keys)
        assert normalized_digests.issubset(raw_digests)
        assert normalized_digests  # non-empty: real reuse happened, not silently dropped

    def test_actor_information_view_never_contains_opponent_hand_cards(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        for decision in result.decisions:
            view = decision.actor_information_view
            assert view is not None
            public_state = view["public_state"]
            opponent = public_state.get("opponent", {})
            # opponent hand must only ever be a count, never a card list
            assert "hand" not in opponent or opponent.get("hand") == []

    def test_quality_flags_document_source_limitations(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        for episode in result.episodes:
            assert "winner_unavailable_in_source" in episode.quality_flags
            assert episode.winner is None

    def test_latency_and_result_to_go_are_none_not_fabricated(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        for decision in result.decisions:
            assert decision.latency_us is None
            assert decision.result_to_go is None

    def test_malformed_rows_are_quarantined_not_fatal(self, rule_bc_jsonl_path: Path, tmp_path: Path) -> None:
        original = rule_bc_jsonl_path.read_text(encoding="utf-8")
        broken_path = tmp_path / "broken.jsonl"
        broken_path.write_text(original + '{"schema_version": "rule-bc-v1"}\n', encoding="utf-8")
        result = normalize_rule_bc_jsonl(broken_path, source_id="local:test-source")
        assert len(result.quarantined_rows) == 1
        assert result.valid_row_count == result.source_row_count - 1

    def test_public_trace_hash_is_deterministic(self, rule_bc_jsonl_path: Path) -> None:
        first = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        second = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        first_hashes = {e.episode_id: e.public_trace_hash for e in first.episodes}
        second_hashes = {e.episode_id: e.public_trace_hash for e in second.episodes}
        assert first_hashes == second_hashes

    def test_first_player_extracted_when_available(self, rule_bc_jsonl_path: Path) -> None:
        result = normalize_rule_bc_jsonl(rule_bc_jsonl_path, source_id="local:test-source")
        assert any(episode.first_player is not None for episode in result.episodes)
