"""Tests for offline_reader.py + phase.py + replay_normalize.py.

Fixtures are generated by calling the *real* Offline Training v1 collector
(``run_collection(source="fixture", ...)``) exactly like
``tests/test_offline_training_v1.py`` does, rather than hand-authoring JSON:
the real writer's hashing/redaction/manifest logic is nontrivial to fake
correctly by hand, and this proves the O1-2 reader against the actual
on-disk contract, not a guess at it. This never touches the actual cabt
engine (``source="fixture"`` drives a deterministic synthetic match runner).
"""

